"""Build native-size Weiguang Home Sans bitmaps from the pinned OFL Noto source.

Requires Pillow 12.1.1. No system fonts, private task names, or network access.
Run: python3 checks/generate_home_fonts.py --source .vendor/noto-home-font
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/fonts"
SPECS = (("status30", "Bold", 30, 36, 28),
         ("title24", "Regular", 24, 30, 23))


def repertoire():
    common = set(range(0x20, 0x7F)) | {0xA0, 0xB7, 0x2026, 0xFFFF}
    # Only public firmware source, never runtime task titles or conversation data.
    for source in sorted((ROOT / "src").glob("*")):
        if source.suffix in (".cpp", ".h"):
            common.update(ord(c) for c in source.read_text() if 0x100 <= ord(c) < 0xFFFF)
    title = common | set(range(0xA0, 0x100)) | set(range(0x2000, 0x2070))
    title |= set(range(0x3000, 0x3040)) | set(range(0x3400, 0xA000))
    title |= set(range(0xFF00, 0xFFF0))
    return sorted(common), sorted(title)


def glyph_bitmap(font, code, size, height, baseline):
    advance = size // 2 if code < 0x100 else size
    # Oversized scratch cell lets us check ink bounds before cropping a glyph.
    scratch = Image.new("L", (size * 4, size * 4))
    draw = ImageDraw.Draw(scratch)
    if code == 0xFFFF:
        draw.rectangle((size + 2, size + baseline - size + 4,
                        size + advance - 3, size + baseline - 2), outline=255)
    else:
        draw.text((size, size + baseline), chr(code), font=font, fill=255, anchor="ls")
    scratch = scratch.point(lambda value: 255 if value >= 128 else 0, "1")
    box = scratch.getbbox()
    x, y = size, size
    # Some punctuation (notably the middle dot) has a full-width source advance;
    # center its ink in the renderer's half-width Latin cell without resampling.
    if box:
        left, top, right, bottom = box
        if right - left <= advance:
            if code < 0x100 and font.getlength(chr(code)) > advance + 0.5:
                x = left - (advance - (right - left)) // 2
            elif left < x:
                x = left
            if right > x + advance:
                x = right - advance
        if bottom - top <= height:
            if top < y:
                y = top
            if bottom > y + height:
                y = bottom - height
    cell = scratch.crop((x, y, x + advance, y + height))
    packed = Image.new("1", (((size + 7) // 8) * 8, height))
    packed.paste(cell, (0, 0))
    return packed.tobytes()


def write_array(file, ctype, name, values, digits, columns):
    file.write(f"static const {ctype} {name}[] = {{\n")
    for start in range(0, len(values), columns):
        file.write(",".join(f"0x{v:0{digits}x}" for v in values[start:start + columns]) + ",\n")
    file.write("};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads((OUTPUT / "sources.json").read_text())
    for item in manifest["files"]:
        content = (args.source / item["file"]).read_bytes()
        if hashlib.sha256(content).hexdigest() != item["sha256"]:
            raise ValueError(f"Source checksum mismatch: {item['file']}")
    common, title = repertoire()
    report = {"pillow": pillow_version, "fonts": []}
    for name, weight, size, height, baseline in SPECS:
        font = ImageFont.truetype(str(args.source / f"NotoSansMonoCJKsc-{weight}.otf"), size)
        codes = title if name == "title24" else common
        assert len(codes) < 65536 and codes[-1] == 0xFFFF
        data = b"".join(glyph_bitmap(font, code, size, height, baseline) for code in codes)
        assert len(data) == len(codes) * height * ((size + 7) // 8)
        path = OUTPUT / f"home_sans_{size}.cpp"
        with path.open("w") as file:
            file.write('// Generated by checks/generate_home_fonts.py; do not edit.\n'
                       '// Weiguang Home Sans, derived from Noto Sans Mono CJK SC.\n'
                       '// Font data: SIL OFL 1.1; see OFL-Noto.txt and README.md.\n'
                       '#include "home_sans.h"\nnamespace HomeSans {\n')
            write_array(file, "uint16_t", "index", codes, 4, 16)
            write_array(file, "uint8_t", "bitmap", data, 2, 32)
            file.write(f'const lgfx::BDFfont {name}(bitmap,index,{len(codes)},'
                       f'{size},{size // 2},{height},{baseline},{height});\n}}\n')
        report["fonts"].append({"name": name, "size": size, "height": height,
                                "baseline": baseline, "glyphs": len(codes),
                                "bitmap_bytes": len(data),
                                "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
        print(f"{name}: {len(codes)} glyphs, {len(data)} bitmap bytes", flush=True)
    (OUTPUT / "generated.json").write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
